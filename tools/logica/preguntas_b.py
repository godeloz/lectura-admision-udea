SITUACIONES = []

def situacion(cod, paq, titulo, contenido, preguntas, fig=None, fuente="Situación original para práctica."):
    SITUACIONES.append(dict(cod=cod, paq=paq, titulo=titulo, contenido=contenido, fig=fig, fuente=fuente, preguntas=preguntas))

def sq(cod, tema, dif, enun, ok, malas, pista, pasos, idea="", chk=None):
    assert len(malas) == 3, cod
    if chk is not None:
        assert chk(), f"Falla la comprobación de {cod}"
    return dict(cod=cod, tema=tema, dif=dif, enun=enun, ok=ok, malas=malas, pista=pista, pasos=pasos, idea=idea, fig=None)

