"""Recorrido de la 1.2.0 sobre demo.html: el tutor crea una cuenta desde el celular,
restablece contraseñas, desactiva y activa, arma un grupo, explora y prueba el banco
y practica como estudiante. Después la persona nueva entra por primera vez: cambia
la contraseña, ve el paso de instalar, entra a su grupo y cambia la contraseña desde
su perfil. Al final revisa las instrucciones de instalación en iPhone y en Android
y que la navegación de seis entradas quepa en un celular angosto.

Antes: python3 tools/construir_demo.py. Necesita Playwright con Chromium.
"""
import asyncio, os, re, tempfile
from playwright.async_api import async_playwright
RAIZ = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
APP = "file://" + RAIZ + "/demo.html"
SH = tempfile.mkdtemp(prefix="entrelineas-capturas-") + "/"
IPHONE = "Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1"
ANDROID = "Mozilla/5.0 (Linux; Android 14; Pixel 8) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Mobile Safari/537.36"
FALLAS = []
def ok(c, m): print(("  ✓ " if c else "  ✗ FALLA: ") + m); c or FALLAS.append(m)

async def premios(pg):
    await asyncio.sleep(.4)
    while await pg.query_selector("dialog .premio"):
        await pg.click("dialog [data-valor]"); await asyncio.sleep(.3)

async def entrar(pg, u, clave="demo", esperar=".nav"):
    await pg.goto(APP + "#/salir"); await pg.wait_for_selector("#f-ingreso")
    await pg.fill("[name=usuario]", u); await pg.fill("[name=clave]", clave); await pg.click("#f-ingreso button")
    if esperar: await pg.wait_for_selector(esperar)

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); errs = []
        ctx = await b.new_context(viewport={"width": 390, "height": 844}, user_agent=ANDROID)
        await ctx.grant_permissions(["clipboard-read", "clipboard-write"])
        pg = await ctx.new_page()
        pg.on("console", lambda m: errs.append(m.text) if m.type == "error" and "ERR_TUNNEL" not in m.text else None)
        pg.on("pageerror", lambda e: errs.append("PAGEERROR " + str(e)))
        await pg.goto(APP); await pg.evaluate("localStorage.clear()")

        print("1. Tutor: Personas")
        await entrar(pg, "tutor")
        navt = await pg.eval_on_selector_all(".nav a", "xs=>xs.map(x=>x.textContent.trim())")
        ok([re.sub(r"^\W+", "", x) for x in navt] == ["Estudiantes", "Personas", "Contenido", "Practicar", "Salir"], f"navegación del tutor: {navt}")
        await pg.click('.nav a[href="#/tutor/personas"]'); await pg.wait_for_selector("#f-persona")
        n0 = len(await pg.query_selector_all(".persona"))
        await pg.fill("#f-persona [name=nombre]", "Laura Restrepo"); await pg.fill("#f-persona [name=correo]", "Laura.R@Correo.com")
        await pg.select_option("#f-persona [name=grupo]", label="🎨 Artes UdeA")
        await pg.click("#f-persona button.btn"); await pg.wait_for_selector("dialog .credenciales")
        clave = (await pg.inner_text("dialog .clave")).strip()
        msg = await pg.input_value("dialog .mensaje-listo")
        wa = await pg.get_attribute('dialog a[href^="https://wa.me/"]', "href")
        ok(re.fullmatch(r"[a-z]+-[a-z]+-\d{3}", clave) is not None, f"contraseña temporal: {clave}")
        ok("laura.r@correo.com" in msg and clave in msg and "demo.html" in msg and "Hola Laura" in msg, "mensaje listo con enlace, correo y contraseña")
        ok(wa and "wa.me" in wa and "laura.r%40correo.com" in wa, "botón de WhatsApp con el mensaje")
        await pg.screenshot(path=SH + "c01-credenciales.png")
        await pg.click('dialog [data-accion="copiarMensaje"]'); await asyncio.sleep(.3)
        ok("Mensaje copiado" in await pg.inner_text(".avisos"), "copiar mensaje")
        await pg.click("dialog [data-valor=ok]"); await pg.wait_for_selector("#f-persona")
        await asyncio.sleep(.3)
        cards = await pg.query_selector_all(".persona")
        laura = [await c.inner_text() for c in cards if "Laura" in await c.inner_text()][0]
        ok(len(cards) == n0 + 1 and "Aún no elige su contraseña" in laura and "Artes UdeA" in laura, "Laura aparece en la lista, en su grupo, pendiente de elegir contraseña")
        await pg.fill("#f-persona [name=nombre]", "Otra"); await pg.fill("#f-persona [name=correo]", "laura.r@correo.com")
        await pg.click("#f-persona button.btn"); await asyncio.sleep(.5)
        ok("Ya existe" in await pg.inner_text("#error-persona"), "correo repetido: avisa en el formulario")
        # contraseña nueva para Mateo y desactivar / activar
        boton = await pg.query_selector('.persona:has-text("Mateo") [data-accion="nuevaClave"]')
        await boton.click(); await pg.click("dialog [data-valor=si]"); await pg.wait_for_selector("dialog .credenciales")
        clave_mateo = (await pg.inner_text("dialog .clave")).strip()
        ok("Contraseña nueva" in await pg.inner_text("dialog h2"), f"contraseña nueva para Mateo: {clave_mateo}")
        await pg.click("dialog [data-valor=ok]"); await asyncio.sleep(.4)
        await (await pg.query_selector('.persona:has-text("Valentina") [data-accion="estadoPersona"]')).click()
        await pg.click("dialog [data-valor=si]"); await asyncio.sleep(.5)
        ok("Desactivada" in await pg.inner_text('.persona:has-text("Valentina")'), "Valentina desactivada")
        await pg.screenshot(path=SH + "c02-personas.png", full_page=True)

        print("2. Tutor: grupos")
        await pg.click('.segmentos a[href="#/tutor/personas/grupos"]'); await pg.wait_for_selector(".grupo-tarjeta")
        await pg.click('[data-accion="editarGrupo"]:not([data-id])'); await pg.wait_for_selector("#f-grupo")
        await pg.fill("#f-grupo [name=nombre]", "Música UdeA"); await pg.click('#f-grupo [data-av="🎵"]'); await pg.check("#f-grupo [name=ver]")
        await pg.click("#f-grupo button[value=ok]"); await pg.wait_for_selector("#f-miembros")
        await pg.check('#f-miembros label:has-text("Laura") input'); await pg.check('#f-miembros label:has-text("Sofía") input')
        await pg.click("#f-miembros button[value=ok]"); await asyncio.sleep(.6)
        ok(await pg.get_attribute('.nav a[aria-current="page"]', "href") == "#/tutor/personas", "en Grupos queda marcada «Personas» en la navegación")
        tarjetas = await pg.eval_on_selector_all(".grupo-tarjeta", "xs=>xs.map(x=>x.innerText.replace(/\\s+/g,' '))")
        ok(any("Música UdeA" in t and "2 personas" in t and "Muestra puntajes" in t for t in tarjetas), f"grupo nuevo con dos personas y puntajes visibles")
        await pg.click('.grupo-tarjeta:has-text("Artes UdeA") a[href^="#/grupo/"]'); await pg.wait_for_selector(".semana")
        filas = await pg.eval_on_selector_all(".semana li", "xs=>xs.map(x=>x.innerText.replace(/\\s+/g,' '))")
        ok(len(filas) == 3 and not any("Valentina" in f for f in filas), f"el tutor ve la semana de Artes sin la cuenta desactivada: {filas}")
        await pg.screenshot(path=SH + "c03-grupo-tutor.png", full_page=True)
        await pg.click('a[href="#/tutor/personas/grupos"]'); await pg.wait_for_selector(".grupo-tarjeta")
        await pg.click('.segmentos a[href="#/tutor/personas"]'); await pg.wait_for_selector(".persona")
        await (await pg.query_selector('.persona:has-text("Valentina") [data-accion="estadoPersona"]')).click(); await asyncio.sleep(.5)
        ok("Desactivada" not in await pg.inner_text('.persona:has-text("Valentina")'), "Valentina activada otra vez")

        print("3. Tutor: explorar el banco")
        await pg.click('.nav a[href="#/tutor/contenido"]'); await pg.wait_for_selector(".destacado")
        await pg.click('a[href="#/tutor/contenido/banco"]'); await pg.wait_for_selector(".bloque-banco")
        nb = len(await pg.query_selector_all(".bloque-banco"))
        ok(await pg.get_attribute('.nav a[aria-current="page"]', "href") == "#/tutor/contenido", "en el banco queda marcada «Contenido» en la navegación")
        await pg.click(".bloque-banco summary"); await pg.wait_for_selector(".pregunta.probar")
        ok(await pg.query_selector(".bloque-banco .lectura") is not None, f"{nb} lecturas; al abrir una se ve el texto y sus preguntas")
        await pg.click(".pregunta.probar .opcion >> nth=0"); await pg.wait_for_selector(".pregunta.probar .retro")
        ok(await pg.query_selector(".pregunta.probar .opcion.bien") is not None, "responder muestra la clave y la explicación")
        await pg.click('[data-accion="probarOtraVez"]'); await asyncio.sleep(.2)
        ok(await pg.query_selector(".pregunta.probar .retro") is None, "«Responder otra vez» la deja como nueva")
        await pg.click('#filtros-banco [data-comp="logica"]'); await pg.wait_for_selector(".bloque-banco")
        await pg.select_option("#filtros-banco [name=cat]", "proporcional"); await asyncio.sleep(.3)
        await pg.click(".bloque-banco summary"); await pg.wait_for_selector(".pregunta.probar")
        await pg.click('.pregunta.probar [data-accion="probarPista"]'); await pg.wait_for_selector(".pregunta.probar .pista-caja")
        q = await pg.query_selector(".pregunta.probar")
        ops = await q.query_selector_all(".opcion")
        # se elige una opción incorrecta para ver el diagnóstico (la correcta no se conoce aquí: se prueba hasta ver «La respuesta era»)
        await ops[0].click(); await pg.wait_for_selector(".pregunta.probar .retro")
        txt = await pg.inner_text(".pregunta.probar .retro")
        ok("Solución paso a paso" in txt or "Compara" in txt or "pasos" in (await pg.inner_html(".pregunta.probar .retro")), "lógica: pista, solución paso a paso y técnica")
        ok(("Qué pasó" in txt) == ("La respuesta era" in txt), "lógica: si falla, dice qué error lleva a esa opción")
        await pg.fill("#filtros-banco [name=q]", "zzzz-nada"); await asyncio.sleep(.8)
        ok("Ninguna pregunta" in await pg.inner_text(".banco"), "el buscador filtra")
        await pg.screenshot(path=SH + "c04-banco.png", full_page=True)

        print("4. Tutor: practicar como estudiante")
        await pg.click('.nav a[href="#/practicar"]'); await pg.wait_for_selector(".banda.practica")
        nav = await pg.eval_on_selector_all(".nav a", "xs=>xs.map(x=>x.getAttribute('href'))")
        ok("#/inicio" in nav and "#/tutor" not in nav and "#/grupo" not in nav, f"en práctica ve la navegación de estudiante: {nav}")
        await pg.click('.track[data-n="5"]'); await pg.wait_for_selector(".opcion")
        for i in range(5):
            await pg.click(".opcion >> nth=1"); await pg.click('[data-accion="confirmar"]'); await pg.wait_for_selector("#btn-sig"); await pg.click("#btn-sig")
        await pg.wait_for_selector(".marcador"); await premios(pg)
        await pg.click('[data-accion="volverInicio"]'); await pg.wait_for_selector(".tracklist")
        await pg.click('.nav a[href="#/perfil"]'); await pg.wait_for_selector('[data-accion="borrarPractica"]')
        ok("Tu práctica de tutor" in await pg.inner_text("#vista"), "su perfil de práctica ofrece borrar la práctica")
        await pg.click('[data-accion="borrarPractica"]'); await pg.click("dialog [data-valor=si]"); await asyncio.sleep(.6)
        ok("0 preguntas" in (await pg.inner_text(".stats")).replace("\n", " ") or (await pg.inner_text(".stats")).split("\n").count("0") >= 2, "borrar práctica deja todo en cero")
        await pg.click('.banda.practica [data-accion="salirPractica"]'); await pg.wait_for_selector(".estudiantes")
        panel = await pg.inner_text(".estudiantes")
        ok("Tutor" not in panel and await pg.query_selector(".banda.practica") is None, "de vuelta al panel; el tutor no aparece como estudiante")

        print("5. La persona nueva entra por primera vez")
        await entrar(pg, "laura.r@correo.com", clave, esperar="#f-clave")
        await pg.fill("#f-clave [name=nueva]", "una-clave-larga"); await pg.fill("#f-clave [name=repetir]", "otra-distinta-1"); await pg.click("#f-clave button.btn")
        ok("no coinciden" in await pg.inner_text("#error-clave"), "si no coinciden, lo dice")
        await pg.fill("#f-clave [name=nueva]", "corta"); await pg.fill("#f-clave [name=repetir]", "corta"); await pg.click("#f-clave button.btn")
        ok("al menos 8" in await pg.inner_text("#error-clave"), "si es corta, lo dice")
        await pg.screenshot(path=SH + "c05-primer-ingreso.png")
        await pg.fill("#f-clave [name=nueva]", "mango con sal"); await pg.fill("#f-clave [name=repetir]", "mango con sal"); await pg.click("#f-clave button.btn")
        await pg.wait_for_selector("#caja-instalar")
        ok("Instalar aplicación" in await pg.inner_text("#caja-instalar"), "último paso: instrucciones de Android")
        await pg.screenshot(path=SH + "c06-paso-instalar.png")
        await pg.click("#b-despues"); await pg.wait_for_selector(".tracklist")
        nav = await pg.eval_on_selector_all(".nav a", "xs=>xs.map(x=>x.getAttribute('href'))")
        ok("#/grupo" in nav and len(nav) == 6, f"navegación con Grupo (seis entradas): {nav}")
        ok(await pg.query_selector(".banda.instalar") is not None, "la franja «Instala Entrelíneas» queda visible arriba")
        await pg.screenshot(path=SH + "c07-inicio-laura.png")
        await pg.click('.nav a[href="#/grupo"]'); await pg.wait_for_selector(".semana")
        segs = await pg.eval_on_selector_all(".saludo .segmentos a", "xs=>xs.map(x=>x.textContent.trim())")
        ok(len(segs) == 2, f"está en dos grupos y puede pasar de uno a otro: {segs}")
        await pg.click('.saludo .segmentos a:has-text("Música")'); await pg.wait_for_function("document.querySelector('#vista h1')?.textContent.includes('Música') && document.querySelector('.semana')")
        filas = await pg.eval_on_selector_all(".semana li", "xs=>xs.map(x=>x.innerText.replace(/\\s+/g,' '))")
        ok(len(filas) == 2 and any("(tú)" in f for f in filas) and any("Sofía" in f for f in filas), f"semana de Música: {filas}")
        ok("ni sus puntajes" not in await pg.inner_text("#vista"), "en Música (con puntajes) la nota no promete ocultarlos")
        await pg.screenshot(path=SH + "c08-grupo-musica.png", full_page=True)
        await pg.click('.saludo .segmentos a:has-text("Artes")'); await pg.wait_for_function("document.querySelector('#vista h1')?.textContent.includes('Artes') && document.querySelector('.semana')")
        ok(len(await pg.query_selector_all(".semana .sims")) == 0 and "ni sus puntajes" in await pg.inner_text("#vista"), "en Artes (solo esfuerzo) no se ven puntajes y la nota lo dice")
        act = await pg.inner_text(".actividad") if await pg.query_selector(".actividad") else ""
        ok("terminó un reto" in act and "%" not in act, "actividad: retos terminados, sin resultados")
        await pg.screenshot(path=SH + "c09-grupo-artes.png", full_page=True)
        await pg.click('.nav a[href="#/perfil"]'); await pg.wait_for_selector('[data-accion="cambiarClave"]')
        perfil = await pg.inner_text("#vista")
        ok("laura.r@correo.com" in perfil and "Ver cómo instalarla" in perfil and "Tu práctica de tutor" not in perfil, "perfil: su correo, instalar la app y cambiar contraseña")
        await pg.click('[data-accion="cambiarClave"]'); await pg.wait_for_selector("#f-cambio")
        await pg.fill("#f-cambio [name=nueva]", "mango sin sal"); await pg.fill("#f-cambio [name=repetir]", "mango sin sal"); await pg.click("#f-cambio button[value=ok]")
        await asyncio.sleep(.5)
        await entrar(pg, "laura.r@correo.com", "mango sin sal")
        ok(await pg.query_selector("#f-clave") is None, "entra con la contraseña nueva y ya no le pide cambiarla")
        await entrar(pg, "mateo", clave_mateo, esperar="#f-clave")
        ok(True, "Mateo, con contraseña restablecida, también debe elegir una nueva")
        await pg.click('#f-clave [data-accion="salir"]'); await pg.wait_for_selector("#f-ingreso")
        ok(True, "desde la pantalla de la contraseña se puede salir")

        print("6. Instrucciones según el teléfono")
        for nombre, ua, esperado in (("iPhone · Safari", IPHONE, "Agregar a inicio"), ("Android · Chrome", ANDROID, "Instalar aplicación")):
            c2 = await b.new_context(viewport={"width": 390, "height": 844}, user_agent=ua)
            p2 = await c2.new_page(); p2.on("pageerror", lambda e: errs.append("PAGEERROR " + str(e)))
            await p2.goto(APP); await p2.wait_for_selector("#f-ingreso")
            await p2.fill("[name=usuario]", "sofia"); await p2.fill("[name=clave]", "demo"); await p2.click("#f-ingreso button"); await p2.wait_for_selector(".nav")
            await p2.click(".banda.instalar a"); await p2.wait_for_selector("#caja-instalar")
            ok(esperado in await p2.inner_text("#caja-instalar"), f"{nombre}: «{esperado}»")
            await p2.screenshot(path=SH + f"c10-instalar-{ua[13:19].strip()}.png", full_page=True)
            await p2.goto(APP + "#/inicio"); await p2.wait_for_selector(".tracklist")
            await p2.click('.banda.instalar [data-accion="ocultarInstalar"]')
            await p2.reload(); await p2.wait_for_selector(".tracklist")
            ok(await p2.query_selector(".banda.instalar") is None, f"{nombre}: la franja se puede esconder unos días")
            await c2.close()
        c3 = await b.new_context(viewport={"width": 1280, "height": 900})
        p3 = await c3.new_page(); await p3.goto(APP); await p3.wait_for_selector("#f-ingreso")
        await p3.fill("[name=usuario]", "sofia"); await p3.fill("[name=clave]", "demo"); await p3.click("#f-ingreso button"); await p3.wait_for_selector(".nav")
        ok(await p3.query_selector(".banda.instalar") is None, "en el computador no aparece la franja de instalar")
        await p3.goto(APP + "#/instalar"); await p3.wait_for_selector("#caja-instalar")
        ok("Esto se hace en el celular" in await p3.inner_text("#caja-instalar"), "en el computador, #/instalar explica que se hace en el celular")
        await c3.close()

        print("7. Navegación de seis entradas en un celular angosto")
        c4 = await b.new_context(viewport={"width": 320, "height": 640}, user_agent=ANDROID)
        p4 = await c4.new_page(); await p4.goto(APP); await p4.wait_for_selector("#f-ingreso")
        await p4.fill("[name=usuario]", "sofia"); await p4.fill("[name=clave]", "demo"); await p4.click("#f-ingreso button"); await p4.wait_for_selector(".nav")
        r = await p4.evaluate("""() => { const n = document.querySelector('.nav'); const as = [...n.querySelectorAll('a')];
            return { n: as.length, sw: document.documentElement.scrollWidth, ancho: innerWidth, desborde: as.some(a => a.scrollWidth > a.clientWidth + 1), abajo: Math.round(n.getBoundingClientRect().bottom) === innerHeight } }""")
        ok(r["n"] == 6 and r["sw"] <= r["ancho"] and not r["desborde"] and r["abajo"], f"seis entradas caben en 320 px y la barra queda abajo: {r}")
        await p4.screenshot(path=SH + "c11-nav-320.png")
        await c4.close()

        print("8. Cuenta desactivada")
        await entrar(pg, "tutor"); await pg.goto(APP + "#/tutor/personas"); await pg.wait_for_selector(".persona")
        await (await pg.query_selector('.persona:has-text("Valentina") [data-accion="estadoPersona"]')).click(); await pg.click("dialog [data-valor=si]"); await asyncio.sleep(.5)
        await entrar(pg, "valentina", esperar=None); await asyncio.sleep(.6)
        ok("desactivada" in await pg.inner_text("#error-ingreso"), "una cuenta desactivada no puede entrar y lo dice")

        ok(not errs, f"sin errores de JavaScript: {errs}")
        print("\nFALLAS:", FALLAS if FALLAS else "ninguna")
        print("Capturas en", SH)
        await b.close()
        raise SystemExit(1 if FALLAS else 0)

asyncio.run(main())
